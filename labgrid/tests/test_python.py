def test_pyc_files_in_rootfs(gateway_system_is_running, shell):
    """The /usr/lib directory contains .pyc files."""
    stdout, _, exit_code = shell.run("find /usr/lib -name '*.pyc' -type f")
    assert exit_code == 0, f"find command failed: {stdout}"
    num_pyc_files = len(stdout)
    # Expected number of .pyc files is just a rough low minimum estimate
    expected_min_num_pyc_files = 500
    assert num_pyc_files > expected_min_num_pyc_files, (
        f"Expected at least {expected_min_num_pyc_files} .pyc files in /usr/lib, but found {num_pyc_files}."
    )


def test_no_py_files_in_rootfs(gateway_system_is_running, shell):
    """The /usr/lib directory does not contain any .py files."""
    stdout, _, exit_code = shell.run("find /usr/lib -name '*.py' -type f")
    assert exit_code == 0, f"find command failed: {stdout}"
    assert not stdout, f"Found .py files in /usr/lib: {stdout}"


def test_no_pycache_folders_in_rootfs(gateway_system_is_running, shell):
    """The /usr/lib directory does not contain any __pycache__ folders."""
    stdout, _, exit_code = shell.run("find /usr/lib -name '__pycache__' -type d")
    assert exit_code == 0, f"find command failed: {stdout}"
    assert not stdout, f"Found __pycache__ folders in /usr/lib: {stdout}"


def test_pyc_files_in_overlay(gateway_system_is_running, shell):
    """.pyc files in the overlay filesystem indicate that they are generated by Python at boot time,
    which should not happen."""
    stdout, _, exit_code = shell.run("find /media/rfs/rw/ -name '*.pyc' -type f")
    assert exit_code == 0, f"find command failed: {stdout}"
    num_pyc_files = len(stdout)
    # There can be one .pyc file for the traceback module.
    assert num_pyc_files <= 1, f"Found unexpected .pyc files in overlay: {stdout}"
    if num_pyc_files == 1:
        assert "traceback" in stdout[0], (
            f"Found unexpected .pyc file in overlay: {stdout[0]}"
        )
